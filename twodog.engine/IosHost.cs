using System;
using System.Runtime.Versioning;

namespace twodog;

/// <summary>Registers the running .NET runtime with the statically linked Godot engine of an iOS app.</summary>
/// <remarks>
/// Experimental. Godot's view controller (from the 2dog.ios package) owns the display link, input and lifecycle;
/// do not call <see cref="Engine.Start"/> on iOS. Call <see cref="Register"/> before the engine is created.
/// </remarks>
[SupportedOSPlatform("ios")]
public static class IosHost
{
    private static readonly object Sync = new();
    private static IntPtr _registered;

    /// <summary>
    /// Registers the game assembly's plugins initializer, <c>TwoDogWebBoot.PluginsInitializer()</c> (generated by
    /// 2dog.godotsharp), with libgodot. GDMono initializes through it instead of loading GodotPlugins.dll, which an
    /// AOT-compiled iOS app does not carry.
    /// </summary>
    public static void Register(IntPtr pluginsInitializer)
    {
        if (!OperatingSystem.IsIOS())
            throw new PlatformNotSupportedException("IosHost requires .NET for iOS.");
        if (pluginsInitializer == IntPtr.Zero)
            throw new ArgumentException("Pass TwoDogWebBoot.PluginsInitializer() from the game project.", nameof(pluginsInitializer));
        lock (Sync)
        {
            if (_registered != IntPtr.Zero)
            {
                if (_registered != pluginsInitializer)
                    throw new InvalidOperationException("IosHost is already registered with another plugins initializer.");
                return;
            }
            // The archive is linked into the app: the logical libgodot name resolves to the main program.
            LibGodotLoader.Register();
            GamePluginsInitializer.Register(pluginsInitializer);
            _registered = pluginsInitializer;
        }
    }

    /// <summary>Whether <see cref="Register"/> ran.</summary>
    public static bool IsRegistered => _registered != IntPtr.Zero;
}
