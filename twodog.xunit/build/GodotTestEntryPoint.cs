using System;
using System.Linq;
using System.Reflection;
using System.Threading.Tasks;

namespace twodog.Testing.Xunit;

/// <summary>
/// The test assembly's entry point (2dog.xunit.targets sets it as StartupObject): runs the one xUnit generates through
/// <see cref="GodotTestThread.RunMain"/>, so that on macOS the 2dog test thread is the process main thread.
/// </summary>
internal static class GodotTestEntryPoint
{
    public static int Main(string[] args)
    {
        var main = FindXunitEntryPoint();
        return GodotTestThread.RunMain(() => Invoke(main, args));
    }

    // xUnit generates <RootNamespace>.AutoGenerated.XunitAutoGeneratedEntryPoint.Main(string[]).
    private static MethodInfo FindXunitEntryPoint()
    {
        Type?[] types;
        try
        {
            types = typeof(GodotTestEntryPoint).Assembly.GetTypes();
        }
        catch (ReflectionTypeLoadException error)
        {
            types = error.Types;
        }

        return types.Where(type => type?.Name == "XunitAutoGeneratedEntryPoint")
                   .Select(type => type!.GetMethod("Main", BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static,
                       [typeof(string[])]))
                   .SingleOrDefault(method => method is not null)
               ?? throw new InvalidOperationException(
                   "2dog.xunit found no xUnit-generated entry point. A project with its own entry point should set "
                   + "StartupObject to it and run its tests through GodotTestThread.RunMain.");
    }

    private static int Invoke(MethodInfo main, string[] args)
        => main.Invoke(null, BindingFlags.DoNotWrapExceptions, null, [args], null) switch
        {
            int exitCode => exitCode,
            Task<int> exitCode => exitCode.GetAwaiter().GetResult(),
            Task task => Complete(task),
            _ => 0,
        };

    private static int Complete(Task task)
    {
        task.GetAwaiter().GetResult();
        return 0;
    }
}
